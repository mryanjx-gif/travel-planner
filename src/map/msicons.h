// 找不到返回 0
inline char32_t codepoint(const char *name)
{
    int lo = 0, hi = int(sizeof(kIcons) / sizeof(kIcons[0])) - 1;
    while (lo <= hi) {
        const int mid = (lo + hi) / 2;
        const int c = std::strcmp(name, kIcons[mid].name);
        if (c == 0) return kIcons[mid].cp;
        if (c < 0) hi = mid - 1; else lo = mid + 1;
    }
    return 0;
}

